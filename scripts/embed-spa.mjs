// After `vite build`: embed public/index.html in a JS module so the Vercel function bundle always contains it
// (static imports are traced; plain fs reads of build output are not).
import fs from 'node:fs';

const html = fs.readFileSync(new URL('../public/index.html', import.meta.url), 'utf8');
fs.writeFileSync(new URL('../src/spa-index.generated.js', import.meta.url), `// generated by scripts/embed-spa.mjs – do not edit\nexport default ${JSON.stringify(html)};\n`);
console.log('embedded public/index.html → src/spa-index.generated.js');
